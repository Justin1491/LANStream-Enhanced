// Uses an existing Playwright installation; no npm dependencies are added.
const {chromium} = require(process.env.LANSTREAM_PLAYWRIGHT || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
let browser;

(async () => {
  const url = process.argv[2] || 'http://127.0.0.1:8061';
  const output = path.resolve(process.argv[3] || 'benchmark-results/browser');
  fs.mkdirSync(output, {recursive:true});
  browser = await chromium.launch({headless:true, chromiumSandbox:true,
    ...(process.env.LANSTREAM_BROWSER ? {executablePath:process.env.LANSTREAM_BROWSER} : {})});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors = [];
  page.on('response', response => { if (response.status() >= 400) console.log('HTTP', response.status(), response.url()); });
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text() + ' ' + message.location().url); });
  const started = performance.now();
  await page.goto(url + '/browse/0/');
  await page.locator('.explorer-item').first().waitFor();
  const firstRenderMs = performance.now() - started;
  assert.equal(await page.locator('.explorer-item').count(), 100);
  const domCount = await page.locator('*').count();
  await page.getByRole('button', {name:'List',exact:true}).click();
  const videoImage = page.locator('.item-preview img').first();
  await videoImage.waitFor({state:'visible'});
  assert.equal(await videoImage.evaluate(node => node.getBoundingClientRect().width), 64);
  await page.screenshot({path:path.join(output,'desktop-list.png')});
  await page.getByRole('button', {name:'Next →',exact:true}).click();
  await page.getByText('Page 2 of 260', {exact:true}).waitFor();
  assert.equal(await page.locator('.explorer-item').count(),100);
  await page.getByLabel('Filter entire folder').fill('025968');
  await page.getByText('Page 1 of 1', {exact:true}).waitFor();
  assert.equal(await page.locator('.explorer-item').count(),1);
  await page.goBack();
  await page.getByText('Page 2 of 260', {exact:true}).waitFor();
  assert.equal(await page.locator('.explorer-item').count(),100);
  await page.goForward();
  await page.getByText('Page 1 of 1', {exact:true}).waitFor();
  const favorite = page.getByRole('button', {name:'Favorite Clip 025968.mp4',exact:true});
  if (await favorite.getAttribute('aria-pressed') !== 'true') await favorite.click();
  await page.locator('.favorite-button[aria-pressed="true"]').waitFor();
  await page.getByRole('link',{name:'Favorites',exact:true}).click();
  await page.getByText('Clip 025968.mp4',{exact:true}).waitFor();
  await page.getByRole('link',{name:'Search',exact:true}).click();
  await page.getByLabel('Filename contains').fill('025968');
  await page.getByText('Clip 025968.mp4',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Details',exact:true}).click();
  await page.screenshot({path:path.join(output,'search-details.png')});
  await page.goto(url + '/browse/0/');
  await page.locator('.explorer-item').first().waitFor();
  await page.getByRole('button',{name:'Grid',exact:true}).click();
  await page.getByLabel('Grid size').focus();
  await page.keyboard.press('ArrowRight');
  await page.screenshot({path:path.join(output,'desktop-grid.png')});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'List',exact:true}).click();
  await page.screenshot({path:path.join(output,'mobile-list.png')});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile overflow');
  await page.reload();
  await page.locator('.explorer-item').first().waitFor();
  assert.equal(await page.getByRole('button',{name:'List',exact:true}).getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.explorer-item').count(),100);
  await page.goto(url + '/video/0/Clip%20025968.mp4');
  assert.equal(await page.locator('.favorite-action').getAttribute('aria-pressed'),'true');
  await page.getByRole('link',{name:'Play',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('video').readyState >= 2);
  if (await page.locator('video').evaluate(video => video.paused)) await page.locator('#togglePlay').click();
  await page.waitForFunction(() => document.querySelector('video').currentTime > .1);
  assert.equal(await page.locator('.favorite-action').getAttribute('aria-pressed'),'true');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),'mobile player overflow');
  await page.screenshot({path:path.join(output,'mobile-player.png')});
  const report = {url,title:await page.title(),first_render_ms:Math.round(firstRenderMs),
    page_items:100,dom_elements:domCount,mobile_width:390,console_errors:errors,
    checks:['list thumbnail64px','pagination bounded100','full-folder filter','browser back/forward','favorites','global search','details','grid density','mobile no overflow','view persistence','detail/player favorite','actual direct playback']};
  fs.writeFileSync(path.join(output,'browser.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  await browser.close();
  assert.deepEqual(errors,[]);
})().catch(error => { console.error(error); process.exitCode=1; }).finally(async () => { if (browser) await browser.close(); });
